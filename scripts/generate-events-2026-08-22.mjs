const csvEscape = (s) => {
  if (s === null || s === undefined) return '';
  s = String(s);
  if (s.includes(',') || s.includes('"') || s.includes('\n')) {
    return '"' + s.replace(/"/g, '""') + '"';
  }
  return s;
};

const makeRow = (e) => {
  const fields = [
    e.event_id,
    e.date,
    e.date_end ?? '',
    e.place_id,
    e.event_type,
    e.headline,
    e.fact_text,
    e.quote ?? '',
    e.confirmed_cases ?? '',
    e.suspected_cases ?? '',
    e.confirmed_deaths ?? '',
    e.suspected_deaths ?? '',
    e.contacts ?? '',
    e.source_id ?? SOURCE,
    e.source_type ?? 'official',
    e.confidence ?? 'high',
    e.data_status ?? 'provisional',
    e.display_priority ?? '1',
    e.display_tier ?? 'secondary',
    e.map_layer ?? 'clinical',
    e.timeline_group,
    e.update_status ?? 'active',
    e.notes ?? '',
  ];
  return fields.map(csvEscape).join(',');
};

